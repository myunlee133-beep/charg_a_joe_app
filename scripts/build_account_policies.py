"""Build native documents and a repeatable SQL seed from the same versioned source."""
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
documents = json.loads((root / 'backend/account/policies.json').read_text(encoding='utf-8'))
statements = ['-- Generated by scripts/build_account_policies.py; do not edit.\nbegin;']
for document in documents:
    document['sha256'] = hashlib.sha256(document['body'].encode()).hexdigest()
    def literal(value):
        return "'" + value.replace("'", "''") + "'"
    values = ','.join(literal(document[key]) for key in ['kind', 'version', 'title', 'body', 'sha256', 'context'])
    statements.append("update public.account_policy_versions set active=false where kind=" + literal(document['kind']) + " and version<>" + literal(document['version']) + ";")
    statements.append("insert into public.account_policy_versions(kind,version,title,body,sha256,context,effective_at) values(" + values + ",'2026-11-03T00:00:00+09:00') on conflict(kind,version) do nothing;")
    # A published version must be immutable, including during a later re-run.
    statements.append("do $$ begin if exists(select 1 from public.account_policy_versions where kind=" + literal(document['kind']) + " and version=" + literal(document['version']) + " and sha256<>" + literal(document['sha256']) + ") then raise exception 'Published policy version is immutable'; end if; end $$;")
statements.append("notify pgrst,'reload schema';\ncommit;")
(root / 'backend/account/002_policy_seed.sql').write_text('\n'.join(statements), encoding='utf-8')
(root / 'ios/Chajajwo/Resources/account-policies.json').write_text(json.dumps(documents, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
print(f'Built {len(documents)} versioned documents')
